import com.siams.kern_prototype.data.db.entity.LayerEntity

/**
 * Слой уже отправлялся на S900 (есть текущий или прежний серверный id): на сервере МОЖЕТ быть его
 * копия. Приложение пока не заменяет и не удаляет снимки на сервере (R04), а успешная отправка не
 * доказывает полноту серверного архива (R06) — поэтому перед пересъёмкой, удалением и очисткой
 * показывается предупреждение. Признак ничего не утверждает о фактическом состоянии сервера.
 * Обнаруживается только ИЗВЕСТНАЯ приложению отправка: при потерянном ответе POST (R06) копия на
 * сервере может существовать без сохранённого id — тогда признак false.
 */
fun LayerEntity.hasServerCopy(): Boolean = remoteImageId != null || staleRemoteImageId != null
